"""Render ``models/<profile>.md`` and ``models/index.md``: one page per model with its files, preset, pi entry,
card facts, config findings, sweep numbers and results. Read-only on the machine.

    python3 tools/model_cards.py

Sources: the owner's preset (``~/.config/llama-cpp/models-preset.ini``), ``configs/pi-production.json``,
``models/notes.json`` (hand-written card facts), the newest speed sweep under the data folder, and ``results/``.
"""
import configparser
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from llm_eval.paths import DATA  # noqa: E402
from llm_eval.preflight import DEFAULT_PRESET  # noqa: E402
from llm_eval.workload import pi_config  # noqa: E402

PLAN = "plans/2026-11-01-task-expansion-and-llama-config.md"
HEADER = "<!-- Generated by tools/model_cards.py; edit models/notes.json or the sources, then re-run. -->\n"


def sweep_rows():
    """{preset: best fitting row} from the newest full speed sweep."""
    sweeps = sorted(DATA.glob("*-speed-sweep/results.jsonl"))
    if not sweeps:
        return {}, None
    best = {}
    for line in sweeps[-1].read_text().splitlines():
        row = json.loads(line)
        if row.get("fits") and (row["preset"] not in best or (row.get("score") or 0) > (best[row["preset"]].get("score") or 0)):
            best[row["preset"]] = row
    return best, sweeps[-1].parent.name


def size_gb(path):
    try:
        return f"{Path(path).expanduser().stat().st_size / 1e9:.1f} GB"
    except OSError:
        return "missing"


def page(name, settings, entry, note, sweep, sweep_name):
    out = [HEADER, f"# {name}\n"]
    if note.get("base"):
        out.append(f"{note['base']}.\n")
    if note.get("card"):
        out.append(f"Card: {note['card']}\n")
    if settings:
        out.append("\n## Files\n")
        for key in ("model", "model-draft", "mmproj"):
            if settings.get(key):
                out.append(f"- {key}: `{settings[key]}` ({size_gb(settings[key])})")
        out.append("\n\n## Preset (as the router loads it)\n")
        out.extend(f"- `{k}` = `{v}`" for k, v in settings.items() if k not in ("model", "model-draft", "mmproj"))
        out.append("")
    if note.get("config"):
        out.append(f"\n## Launch config\n\n`{note['config']}` (frozen; the plan records its hash)\n")
    if entry:
        level = pi_config.clamp_level(entry, "max") if entry.get("reasoning") else "off"
        out.append("\n## pi entry\n")
        out.append(f"- contextWindow {entry.get('contextWindow')}, maxTokens {entry.get('maxTokens')}, input "
                   f"{', '.join(entry.get('input') or ['text (default)'])}")
        out.append(f"- Thinking at the owner's default `max`: **{level}**")
        kwargs = (entry.get("compat") or {}).get("chatTemplateKwargs") or {}
        if kwargs:
            out.append(f"- Sent as template kwargs: {', '.join(f'`{k}`' for k in kwargs)}")
        out.append("")
    if note.get("card_sampling") or note.get("template"):
        out.append("\n## From the card and the template\n")
        if note.get("card_sampling"):
            out.append(f"- Sampling: {note['card_sampling']}")
        if note.get("template"):
            out.append(f"- Template: {note['template']}")
        out.append("")
    if note.get("known_issues"):
        out.append("\n## Known issues\n")
        out.extend(f"- {issue}" for issue in note["known_issues"])
        out.append("")
    if note.get("findings"):
        out.append(f"\n## Config findings\n\n{', '.join(note['findings'])}: see `{PLAN}`.\n")
    if note.get("config_results"):
        out.append("\n## Config results\n")
        out.extend(f"- {line}" for line in note["config_results"])
        out.append("")
    if sweep:
        out.append(f"\n## Speed ({sweep_name}, llama.cpp build 12017)\n")
        out.append(f"- prefill {sweep.get('prefill_tps')} t/s, decode {sweep.get('decode_tps')} t/s "
                   f"(short {sweep.get('short_decode_tps')}, deep {sweep.get('deep_decode_tps')}), draft acceptance "
                   f"{sweep.get('accept')}, lowest free {sweep.get('min_free_mib')} MiB\n")
    results = sorted((REPO / "results").glob(f"{name}/*.md")) + [REPO / r for r in note.get("results", [])]
    out.append("\n## Results\n")
    out.extend(f"- `{r.relative_to(REPO)}`" for r in dict.fromkeys(results) if r.exists())
    if not any(r.exists() for r in results):
        out.append("- none yet")
    return "\n".join(out).rstrip() + "\n"


def main():
    presets = configparser.ConfigParser(interpolation=None)
    presets.optionxform = str
    presets.read(DEFAULT_PRESET)
    pi = json.loads((REPO / "configs/pi-production.json").read_text())["models"]
    notes = json.loads((REPO / "models/notes.json").read_text())
    sweep, sweep_name = sweep_rows()
    names = sorted(set(presets.sections()) | {"strata"})
    rows = []
    for name in names:
        settings = dict(presets[name]) if presets.has_section(name) else {}
        note = notes.get(name, {})
        (REPO / "models" / f"{name}.md").write_text(page(name, settings, pi.get(name), note, sweep.get(name), sweep_name))
        rows.append(f"| [{name}.md]({name}.md) | {note.get('base', '')} |")
    (REPO / "models" / "index.md").write_text(
        HEADER + "# models\n\nOne page per model the benchmark runs. Facts that are not in the preset or the pi "
        "config live in `notes.json`.\n\n| File | Model |\n|---|---|\n" + "\n".join(rows) + "\n")
    print(f"{len(names)} model pages")


if __name__ == "__main__":
    main()
