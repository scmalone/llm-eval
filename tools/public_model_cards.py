"""Render public model summaries from results/bench-v2.json into an explicit output directory."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    data = json.loads((root / 'results/bench-v2.json').read_text())
    args.output.mkdir(parents=True, exist_ok=True)
    header = '<!-- Generated by tools/public_model_cards.py from results/bench-v2.json. -->\n\n'
    index = header + '# Published benchmark profiles\n\nThese summaries describe the measured core campaigns. Other experiments remain in the private development repository. Unlisted settings are not asserted here.\n\n'
    for row in data['models']:
        name = row['profile'] + '.md'
        index += f"- [{row['model']}]({name}) | {row['core_run_dates'][0]} | {row['context_tokens']:,} tokens; {row['raw_core_passes']}/105 raw core\n"
        text = header + f"# {row['model']}\n\n[Publisher model card]({row['publisher_url']})\n\n"
        text += '| Measured field | Value |\n|---|---|\n'
        fields = {'Profile': row['profile'], 'Engine': row['engine'], 'Context tokens': row['context_tokens'], 'Campaign dates': ' to '.join(row['core_run_dates']), 'Raw core': f"{row['raw_core_passes']}/105", **row['measured_settings']}
        for key, value in fields.items():
            text += f'| {key} | {value} |\n'
        text += '\nProfile names are identifiers and may describe an earlier setup. MTP in a profile name does not mean MTP was enabled in this campaign.\n\nFull counts, adjustment rules and limitations: [benchmark results](../results/bench-v2.json). These summaries are transcribed from private operator records; raw trials are not included.\n'
        (args.output / name).write_text(text)
    (args.output / 'index.md').write_text(index)


if __name__ == '__main__':
    main()
